-- =============================================================================
-- SPM: Anwendungstabellen (getrennt von den LILAM-Tabellen, Präfix SPM_)
-- Zeitstempel in SPM_PRICE als TIMESTAMP in UTC: Eindeutigkeitsschlüssel auf
-- TIMESTAMP WITH TIME ZONE sind in Oracle nicht zulässig (ORA-02329).
-- =============================================================================

-- Konfiguration (Schlüssel/Wert), keine Geheimnisse
create table if not exists spm_config (
    param_name   varchar2(50)  not null,
    param_value  varchar2(400),
    description  varchar2(400),
    constraint spm_config_pk primary key (param_name)
);

-- Kursanbieter; CREDENTIAL_NAME verweist auf eine sichere Ablage, nie auf den Schlüssel selbst
create table if not exists spm_provider (
    provider_code    varchar2(20)  not null,
    provider_name    varchar2(100) not null,
    base_url         varchar2(400),
    credential_name  varchar2(100),
    is_active        varchar2(1)   default 'Y' not null,
    note             varchar2(400),
    constraint spm_provider_pk primary key (provider_code),
    constraint spm_provider_active_chk check (is_active in ('Y', 'N'))
);

-- Watchlist. SYMBOL ist die normalisierte Kennung und zugleich der LILAM-Context.
create table if not exists spm_instrument (
    instrument_id       number generated by default as identity,
    symbol              varchar2(20)  not null,
    provider_code       varchar2(20)  not null,
    provider_symbol     varchar2(40)  not null,
    instrument_name     varchar2(100),
    exchange            varchar2(20),
    currency            varchar2(3)   not null,
    is_active           varchar2(1)   default 'Y' not null,
    last_fetch_at       timestamp with time zone,
    last_fetch_status   varchar2(20),
    last_fetch_message  varchar2(400),
    created_at          timestamp with time zone default systimestamp not null,
    updated_at          timestamp with time zone,
    constraint spm_instrument_pk primary key (instrument_id),
    constraint spm_instrument_symbol_uk unique (symbol),
    constraint spm_instrument_prov_uk unique (provider_code, provider_symbol),
    constraint spm_instrument_provider_fk foreign key (provider_code) references spm_provider (provider_code),
    constraint spm_instrument_symbol_chk check (regexp_like(symbol, '^[A-Z0-9][A-Z0-9.-]{0,19}$')),
    constraint spm_instrument_ccy_chk check (regexp_like(currency, '^[A-Z]{3}$')),
    constraint spm_instrument_active_chk check (is_active in ('Y', 'N'))
);

-- Abrufläufe: Anwendungszustand für Dashboard, Freshness-Prüfung und Watchdog.
-- Verweist über LILAM_PROCESS_ID auf den LILAM-Prozess des Laufs.
create table if not exists spm_run (
    run_id            number generated always as identity,
    trigger_type      varchar2(20)  not null,
    symbol_filter     varchar2(40),
    started_at        timestamp with time zone default systimestamp not null,
    ended_at          timestamp with time zone,
    status            varchar2(20)  not null,
    lilam_process_id  number(19,0),
    cnt_active        number default 0 not null,
    cnt_requested     number default 0 not null,
    cnt_fetched       number default 0 not null,
    cnt_failed        number default 0 not null,
    cnt_stored        number default 0 not null,
    cnt_duplicate     number default 0 not null,
    message           varchar2(1000),
    constraint spm_run_pk primary key (run_id),
    constraint spm_run_status_chk check (status in ('RUNNING', 'SUCCESS', 'PARTIAL', 'FAILED', 'SKIPPED'))
);

create index if not exists spm_run_started_ix on spm_run (started_at);

-- Fachliche Kurshistorie. Eindeutig je Instrument und Quote-Zeitpunkt (Idempotenz).
create table if not exists spm_price (
    price_id       number generated always as identity,
    instrument_id  number        not null,
    price          number        not null,
    currency       varchar2(3)   not null,
    quote_ts_utc   timestamp     not null,
    received_at    timestamp with time zone default systimestamp not null,
    run_id         number,
    provider_code  varchar2(20)  not null,
    constraint spm_price_pk primary key (price_id),
    constraint spm_price_uk unique (instrument_id, quote_ts_utc),
    constraint spm_price_instrument_fk foreign key (instrument_id) references spm_instrument (instrument_id),
    constraint spm_price_run_fk foreign key (run_id) references spm_run (run_id),
    constraint spm_price_positive_chk check (price > 0)
);

create index if not exists spm_price_run_ix on spm_price (run_id);

-- Regelkonfiguration je Instrument; daraus erzeugt SPM_RULES das LILAM Rule Set.
-- NULL = Regel entfällt. EWMA: Abweichung in Prozent vom gleitenden Mittel (nach oben/unten);
-- Warm-up und Alpha gelten für die Wertreihe des Symbols (NULL = LILAM-Standard 3 bzw. 0,1).
create table if not exists spm_rule (
    instrument_id     number       not null,
    val_min           number,
    val_max           number,
    ewma_pct_up       number,
    ewma_pct_down     number,
    ewma_warmup       number,
    ewma_alpha        number,
    severity_limit    varchar2(30) default 'ALARM'   not null,
    severity_ewma     varchar2(30) default 'WARNUNG' not null,
    throttle_seconds  number       default 3600    not null,
    is_active         varchar2(1)  default 'Y'     not null,
    updated_at        timestamp with time zone default systimestamp not null,
    constraint spm_rule_pk primary key (instrument_id),
    constraint spm_rule_instrument_fk foreign key (instrument_id) references spm_instrument (instrument_id),
    constraint spm_rule_minmax_chk check (val_min is null or val_max is null or val_min < val_max),
    constraint spm_rule_pct_chk check ((ewma_pct_up is null or ewma_pct_up > 0) and (ewma_pct_down is null or ewma_pct_down > 0)),
    constraint spm_rule_warmup_chk check (ewma_warmup is null or (ewma_warmup >= 1 and ewma_warmup = trunc(ewma_warmup))),
    constraint spm_rule_alpha_chk check (ewma_alpha is null or (ewma_alpha > 0 and ewma_alpha <= 1)),
    constraint spm_rule_throttle_chk check (throttle_seconds >= 0),
    constraint spm_rule_active_chk check (is_active in ('Y', 'N'))
);

-- Schweige-Regel je Instrument (LILAM TIME_MAX_SILENCE_SECONDS): seit SILENCE_SECONDS kein neuer Kurs.
-- SILENCE_WINDOWS: JSON-Array der LILAM-Zeitfenster, z. B. Handelszeiten; dann SILENCE_TIME_ZONE Pflicht.
declare
    procedure add_column(p_column varchar2, p_definition varchar2) is
        l_count pls_integer;
    begin
        select count(*) into l_count from user_tab_columns
        where  table_name = 'SPM_RULE' and column_name = upper(p_column);
        if l_count = 0 then
            execute immediate 'alter table spm_rule add (' || p_column || ' ' || p_definition || ')';
        end if;
    end add_column;
begin
    add_column('silence_seconds',   'number');
    add_column('silence_windows',   'varchar2(4000)');
    add_column('silence_time_zone', 'varchar2(64)');
    add_column('severity_silence',  'varchar2(30) default ''WARNUNG''');
end;
/

begin
    execute immediate 'alter table spm_rule add constraint spm_rule_silence_chk check (silence_seconds is null or silence_seconds > 0)';
exception
    when others then
        if sqlcode <> -2264 then raise; end if; -- Constraint existiert
end;
/

begin
    execute immediate 'alter table spm_rule add constraint spm_rule_windows_json_chk check (silence_windows is json)';
exception
    when others then
        if sqlcode not in (-2264, -40664) then raise; end if; -- Constraint existiert
end;
/

-- Zustellung von Alerts (SPM_NOTIFY): ein Eintrag je Zustellversuch eines LILAM-Alerts.
-- Ohne Geheimnisse; der Text ist der versendete Mailtext.
create table if not exists spm_notification (
    notification_id  number generated always as identity,
    alert_id         number        not null,
    rule_id          varchar2(50),
    alert_severity   varchar2(30),
    transport        varchar2(20)  not null,
    recipients       varchar2(1000),
    subject          varchar2(400),
    body             clob,
    status           varchar2(20)  not null,
    error_message    varchar2(1000),
    created_at       timestamp with time zone default systimestamp not null,
    constraint spm_notification_pk primary key (notification_id),
    constraint spm_notification_status_chk check (status in ('SENT', 'ERROR'))
);

create index if not exists spm_notification_alert_ix on spm_notification (alert_id);

-- HTML-Fassung der Mail (BODY = Textfassung)
declare
    l_count pls_integer;
begin
    select count(*) into l_count from user_tab_columns
    where  table_name = 'SPM_NOTIFICATION' and column_name = 'BODY_HTML';
    if l_count = 0 then
        execute immediate 'alter table spm_notification add (body_html clob)';
    end if;
end;
/

-- Dringlichkeit auf deutsche Stufen umstellen (vorhandene Installationen; wiederholbar)
begin
    execute immediate q'[alter table spm_rule modify (severity_limit default 'ALARM', severity_ewma default 'WARNUNG', severity_silence default 'WARNUNG')]';
    for c in (select column_value col from table(sys.odcivarchar2list('SEVERITY_LIMIT', 'SEVERITY_EWMA', 'SEVERITY_SILENCE'))) loop
        execute immediate 'update spm_rule set ' || c.col || ' = case ' || c.col
            || q'[ when 'INFO' then 'HINWEIS' when 'WARN' then 'WARNUNG' when 'ERROR' then 'ALARM' when 'CRITICAL' then 'KRITISCH' end]'
            || ' where ' || c.col || q'[ in ('INFO', 'WARN', 'ERROR', 'CRITICAL')]';
    end loop;
    commit;
end;
/

-- Mock-Provider: vorbereitete Antworten je Provider-Symbol, der Reihe nach (SEQ_NO)
-- abgespielt. Platzhalter im BODY: {NOW}, {NOW-<n>M}, {YESTERDAY_NOON} (UTC, ISO 8601).
-- HTTP_STATUS 0 simuliert einen Verbindungsfehler (systemisch, z. B. ACL/TLS).
create table if not exists spm_mock_response (
    provider_symbol   varchar2(40) not null,
    seq_no            number       not null,
    http_status       number       default 200 not null,
    simulate_timeout  varchar2(1)  default 'N' not null,
    body              clob,
    note              varchar2(200),
    constraint spm_mock_response_pk primary key (provider_symbol, seq_no),
    constraint spm_mock_timeout_chk check (simulate_timeout in ('Y', 'N'))
);

-- Mock-Provider: zuletzt abgespielte Antwort je Provider-Symbol
create table if not exists spm_mock_state (
    provider_symbol  varchar2(40) not null,
    last_seq_no      number       not null,
    constraint spm_mock_state_pk primary key (provider_symbol)
);
